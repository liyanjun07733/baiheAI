import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const scriptDir = path.dirname(__filename);
const projectRoot = path.resolve(scriptDir, "..");
const productRoot = path.join(projectRoot, "product-files");

const publicOut = path.join(projectRoot, "app", "tools", "lib", "products.generated.ts");
const serverOut = path.join(projectRoot, "app", "tools", "api", "paddle", "_products.generated.ts");

function fail(message) {
  console.error(`\n[products:sync] ERROR: ${message}\n`);
  process.exit(1);
}

if (!fs.existsSync(productRoot)) fail(`Missing folder: ${productRoot}`);

const folders = fs.readdirSync(productRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_"))
  .map((entry) => entry.name)
  .sort();

const products = [];
const seenSlugs = new Set();
const seenPriceIds = new Set();

for (const folder of folders) {
  const folderPath = path.join(productRoot, folder);
  const manifestPath = path.join(folderPath, "product.json");
  if (!fs.existsSync(manifestPath)) continue;

  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  } catch (error) {
    fail(`${manifestPath} is not valid JSON: ${error.message}`);
  }

  manifest.slug = manifest.slug || folder;
  manifest.pagePath = manifest.pagePath || `/product/${manifest.slug}`;

  const required = ["slug", "code", "name", "priceId", "priceText", "version", "file", "pagePath"];
  for (const key of required) {
    if (!manifest[key] || typeof manifest[key] !== "string") {
      fail(`${manifestPath}: missing string field \"${key}\"`);
    }
  }

  if (!/^[a-z0-9][a-z0-9-]*$/.test(manifest.slug)) {
    fail(`${manifestPath}: slug must use lowercase letters, numbers and hyphens only`);
  }
  if (!manifest.priceId.startsWith("pri_")) fail(`${manifestPath}: priceId must start with pri_`);
  if (!manifest.pagePath.startsWith("/")) fail(`${manifestPath}: pagePath must start with /`);
  if (seenSlugs.has(manifest.slug)) fail(`Duplicate slug: ${manifest.slug}`);
  if (seenPriceIds.has(manifest.priceId)) fail(`Duplicate Paddle priceId: ${manifest.priceId}`);

  const filePath = path.join(folderPath, manifest.file);
  if (!fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
    fail(`${manifestPath}: delivery file not found: ${filePath}`);
  }

  const bytes = fs.readFileSync(filePath);
  const sha256 = crypto.createHash("sha256").update(bytes).digest("hex");

  products.push({
    slug: manifest.slug,
    code: manifest.code,
    name: manifest.name,
    priceId: manifest.priceId,
    priceText: manifest.priceText,
    version: manifest.version,
    fileName: manifest.file,
    pagePath: manifest.pagePath,
    description: manifest.description || "",
    descriptionEn: manifest.descriptionEn || "",
    highlights: Array.isArray(manifest.highlights) ? manifest.highlights.map(String) : [],
    enabled: manifest.enabled !== false,
    bytes: bytes.length,
    sha256,
    base64: bytes.toString("base64"),
  });

  seenSlugs.add(manifest.slug);
  seenPriceIds.add(manifest.priceId);
}

if (products.length === 0) fail("No products found. Add product-files/<slug>/product.json first.");

fs.mkdirSync(path.dirname(publicOut), { recursive: true });
fs.mkdirSync(path.dirname(serverOut), { recursive: true });

const publicProducts = products.map(({ base64, ...item }) => item);

const publicSource = `// AUTO-GENERATED by scripts/sync-products.mjs\n// Do not edit manually. Edit product-files/<slug>/product.json and run the sync script.\n\nexport type ProductDefinition = {\n  slug: string;\n  code: string;\n  name: string;\n  priceId: string;\n  priceText: string;\n  version: string;\n  fileName: string;\n  pagePath: string;\n  description: string;\n  descriptionEn: string;\n  highlights: readonly string[];\n  enabled: boolean;\n  bytes: number;\n  sha256: string;\n};\n\nexport const PRODUCTS = ${JSON.stringify(publicProducts, null, 2)} as const satisfies readonly ProductDefinition[];\n\nexport function getProductBySlug(slug: string) {\n  return PRODUCTS.find((product) => product.slug === slug);\n}\n\nexport function getProductByPriceId(priceId: string) {\n  return PRODUCTS.find((product) => product.priceId === priceId);\n}\n`;

const serverProducts = products.map((item) => ({ ...item }));
const serverSource = `// AUTO-GENERATED by scripts/sync-products.mjs\n// Server-only delivery data. Do not import this module from client components.\n\nexport type ServerProductDefinition = {\n  slug: string;\n  code: string;\n  name: string;\n  priceId: string;\n  priceText: string;\n  version: string;\n  fileName: string;\n  pagePath: string;\n  description: string;\n  descriptionEn: string;\n  highlights: readonly string[];\n  enabled: boolean;\n  bytes: number;\n  sha256: string;\n  base64: string;\n};\n\nexport const SERVER_PRODUCTS = ${JSON.stringify(serverProducts, null, 2)} as const satisfies readonly ServerProductDefinition[];\n\nexport function getServerProductBySlug(slug: string) {\n  return SERVER_PRODUCTS.find((product) => product.slug === slug);\n}\n\nexport function getServerProductByPriceId(priceId: string) {\n  return SERVER_PRODUCTS.find((product) => product.priceId === priceId);\n}\n`;

fs.writeFileSync(publicOut, publicSource, "utf8");
fs.writeFileSync(serverOut, serverSource, "utf8");

console.log("\nBaiheAI product delivery library synchronized successfully.");
console.log(`Products: ${products.length}`);
for (const p of products) {
  console.log(`- ${p.code} | ${p.name} | ${p.priceText} | ${p.fileName} | ${(p.bytes / 1024).toFixed(1)} KB`);
}
console.log(`\nGenerated:\n- ${path.relative(projectRoot, publicOut)}\n- ${path.relative(projectRoot, serverOut)}\n`);
